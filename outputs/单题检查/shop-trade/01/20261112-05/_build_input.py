def build_checks(profile):
    spec = {r['id']: r for r in profile['requirements']}
    seen = {}
    rows = []
    for t in CHECKS:
        cid, status, quality, owner, reason, fix, qb, ev, iss = t
        if cid in seen:
            if seen[cid] != t:
                print('note: %s 存在措辞不同的重复登记，保留首次登记' % cid)
            continue
        seen[cid] = t
        s = spec[cid]
        row = dict(s)
        row.update({'status': status, 'quality': quality, 'owner': owner,
                    'reason': reason, 'fix': fix, 'quality_basis': qb,
                    'evidence': list(ev), 'issue_ids': list(iss)})
        rows.append(row)
    missing = set(spec) - set(seen)
    extra = set(seen) - set(spec)
    assert not missing, f'缺少评分项: {sorted(missing)}'
    assert not extra, f'多余评分项: {sorted(extra)}'
    return rows


def build_issues():
    fields = ('id', 'root_cause', 'fact', 'source', 'impact', 'fix', 'retest', 'history',
              'deduction_basis', 'deduplication', 'certainty', 'owner', 'evidence')
    rows = []
    for t in ISSUES:
        if len(t) == 13:
            t = t[:8] + (ISSUE_BASIS[t[0]],) + t[8:]
        assert len(t) == 14, 'issue field count: %s' % t[0]
        row = dict(zip(fields, t[:13]))
        row['deductions'] = [{'check_id': d[0], 'axis': d[1], 'independent_impact': d[2]}
                             for d in t[13]]
