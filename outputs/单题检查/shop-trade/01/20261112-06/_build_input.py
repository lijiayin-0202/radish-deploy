def build_issues():
    fields = ('id', 'root_cause', 'fact', 'source', 'impact', 'fix', 'retest', 'history',
              'deduction_basis', 'deduplication', 'certainty', 'owner', 'evidence')
    rows = []
    for t in ISSUES:
        if len(t) == 13:
            t = t[:8] + (ISSUE_BASIS[t[0]], ISSUE_DEDUP[t[0]]) + t[9:]
        assert len(t) == 14, 'issue field count: %s' % t[0]
        row = dict(zip(fields, t[:13]))
        row['deductions'] = [{'check_id': d[0], 'axis': d[1], 'independent_impact': d[2]}
                             for d in t[13]]
        rows.append(row)
    return rows


